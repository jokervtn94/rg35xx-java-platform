hashcheck "$RUNTIME/bin/jamvm" "$EXPECTED_JAMVM"
hashcheck "$RUNTIME/share/classpath/glibj.zip" "$EXPECTED_GLIBJ"
hashcheck "$RUNTIME/share/jamvm/classes.zip" "$EXPECTED_CLASSES"
