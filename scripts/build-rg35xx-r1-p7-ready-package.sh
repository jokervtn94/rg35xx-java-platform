set -e
echo "P7_VUA_PROCESS_EXIT=$VRC" >>"$MASTER"
echo "VUA_PROCESS_EXIT=$VRC" >>"$SUMMARY"
[ "$VRC" -eq 0 ] || fail "VUA_JVM_EXIT:$VRC"
