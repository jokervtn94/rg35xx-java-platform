import sys,zipfile
jar=sys.argv[1]
required={
 'RG35XXP2AImageDecodeExerciser.class',
 'RG35XXP2AImageDecodeExerciser$P2ACanvas.class',
 'META-INF/MANIFEST.MF',
 'p2a/expected.tsv',
 'p2a/fixture-manifest.tsv',
}
majors=set()
with zipfile.ZipFile(jar) as z:
    names=set(z.namelist()); missing=required-names
    if missing: raise SystemExit('P2A_EXERCISER_JAR_GATE_FAIL missing='+repr(sorted(missing)))
    pngs=sorted(n for n in names if n.startswith('p2a/f') and n.endswith('.png'))
    if len(pngs)!=150: raise SystemExit('P2A_EXERCISER_JAR_GATE_FAIL png-count=%d'%len(pngs))
    classes=sorted(n for n in names if n.endswith('.class'))
    expected_classes=['RG35XXP2AImageDecodeExerciser$P2ACanvas.class','RG35XXP2AImageDecodeExerciser.class']
    if classes!=expected_classes: raise SystemExit('P2A_EXERCISER_JAR_GATE_FAIL classes='+repr(classes))
    blob=b''.join(z.read(n) for n in classes)
    for marker in (b'P2A_EXERCISER_BOOT=PASS',b'P2A_EXERCISER_RESULT=',b'P2A_EXERCISER_FIXTURE_COUNT=',b'BYTES',b'STREAM',b'RESOURCE'):
        if marker not in blob: raise SystemExit('P2A_EXERCISER_MARKER_GATE_FAIL '+repr(marker))
    if b'RG35XXCore2D' in blob: raise SystemExit('P2A_EXERCISER_DIRECT_DECODER_CALL_FORBIDDEN')
    for n in classes:
        b=z.read(n)
        if b[:4]!=b'\xca\xfe\xba\xbe': raise SystemExit('bad class magic '+n)
        major=int.from_bytes(b[6:8],'big'); majors.add(major)
        if major>50: raise SystemExit('P2A_EXERCISER_JAVA6_FAIL %s major=%d'%(n,major))
print('P2A_EXERCISER_CLASS_MAJORS='+','.join(map(str,sorted(majors))))
print('P2A_EXERCISER_JAVA6_GATE=PASS')
print('P2A_EXERCISER_RESOURCE_COUNT=150')
print('P2A_EXERCISER_DIRECT_DECODER_CALL=NO')
