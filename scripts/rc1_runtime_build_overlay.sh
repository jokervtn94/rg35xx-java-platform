#!/bin/sh
set -eu

# RGJ-RC1-011K/011M/011N/011O — GNU Classpath/runtime + native Make overlay gate.
# Operates only on disposable assembled trees.
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
: "${RG35XX_ASSEMBLY_ROOT:?set RG35XX_ASSEMBLY_ROOT to the 011J assembled FreeJ2ME tree}"
: "${RG35XX_CLASSPATH_ROOT:?set RG35XX_CLASSPATH_ROOT to GNU Classpath 0.99 source}"
: "${RG35XX_RUNTIME_ASSEMBLY_ROOT:?set RG35XX_RUNTIME_ASSEMBLY_ROOT to a disposable GNU Classpath output tree}"
: "${RG35XX_FONT_FILE:?set RG35XX_FONT_FILE to materialized DejaVuSans.ttf}"
: "${RG35XX_FONT_RUNTIME_PATH:?set RG35XX_FONT_RUNTIME_PATH to the absolute target-device DejaVuSans.ttf path}"

fail() { echo "RC1 RUNTIME OVERLAY: FAIL: $*" >&2; exit 1; }
note() { echo "RC1 RUNTIME OVERLAY: $*"; }

LIBRETRO_ROOT="$RG35XX_ASSEMBLY_ROOT/src/libretro"
MAKE_COMMON="$LIBRETRO_ROOT/Makefile.common"
MAKE_OVERLAY="$LIBRETRO_ROOT/rg35xx/rc1_make_overlay.mk"
SOURCES_OVERLAY="$LIBRETRO_ROOT/rg35xx/rc1_sources.mk"

[ -f "$LIBRETRO_ROOT/freej2me_libretro.c" ] || fail "011J assembled FreeJ2ME tree missing"
[ -f "$SOURCES_OVERLAY" ] || fail "011J native source manifest missing"
[ -f "$MAKE_COMMON" ] || fail "pinned Makefile.common missing"
[ -f "$RG35XX_CLASSPATH_ROOT/gnu/java/awt/peer/headless/HeadlessToolkit.java" ] || fail "GNU Classpath 0.99 HeadlessToolkit missing"
[ -s "$RG35XX_FONT_FILE" ] || fail "DejaVu font input missing"
[ "$RG35XX_RUNTIME_ASSEMBLY_ROOT" != "$RG35XX_CLASSPATH_ROOT" ] || fail "runtime assembly must not mutate Classpath source"
case "$RG35XX_FONT_RUNTIME_PATH" in /*) ;; *) fail "font runtime path must be absolute" ;; esac

# Guard the exact pinned Makefile.common shape before modifying the disposable tree.
grep -q '^SOURCES_C += freej2me_libretro\.c$' "$MAKE_COMMON" || fail "unexpected Makefile.common core source owner"
grep -q '^INCLUDES += -Ideps/libretro-common/include$' "$MAKE_COMMON" || fail "unexpected Makefile.common include baseline"
if grep -q 'rg35xx/rc1_make_overlay\.mk' "$MAKE_COMMON"; then
  fail "RG35XX Make overlay already included before 011O integration"
fi

RG35XX_CLASSPATH_ROOT="$RG35XX_CLASSPATH_ROOT" RG35XX_FONT_FILE="$RG35XX_FONT_FILE" \
  sh "$ROOT/scripts/rc1_classpath_preflight.sh"

rm -rf "$RG35XX_RUNTIME_ASSEMBLY_ROOT"
mkdir -p "$RG35XX_RUNTIME_ASSEMBLY_ROOT"
( cd "$RG35XX_CLASSPATH_ROOT" && tar --exclude=.git -cf - . ) | ( cd "$RG35XX_RUNTIME_ASSEMBLY_ROOT" && tar -xf - )

RG35XX_CLASSPATH_ROOT="$RG35XX_RUNTIME_ASSEMBLY_ROOT" \
RG35XX_FONT_FILE="$RG35XX_FONT_FILE" \
RG35XX_FONT_RUNTIME_PATH="$RG35XX_FONT_RUNTIME_PATH" \
  sh "$ROOT/runtime/classpath/apply_rg35xx_font_overlay.sh"

# Historical RG35XX/JamVM evidence shows GNU Classpath 0.99 can overflow the
# fixed Zone point array while expanding compound TrueType glyphs. Apply the
# narrow, guarded capacity correction in the same disposable runtime tree.
RG35XX_CLASSPATH_ROOT="$RG35XX_RUNTIME_ASSEMBLY_ROOT" \
  sh "$ROOT/runtime/classpath/apply_rg35xx_compound_glyph_fix.sh"

PEER="$RG35XX_RUNTIME_ASSEMBLY_ROOT/gnu/java/awt/peer/headless/HeadlessToolkit.java"
OT="$RG35XX_RUNTIME_ASSEMBLY_ROOT/gnu/java/awt/font/OpenTypeFontPeer.java"
ZONE="$RG35XX_RUNTIME_ASSEMBLY_ROOT/gnu/java/awt/font/opentype/truetype/Zone.java"
FONT_STAGE="$RG35XX_RUNTIME_ASSEMBLY_ROOT/resource/rg35xx/DejaVuSans.ttf"
grep -q 'new OpenTypeFontPeer(logical, attrKey)' "$PEER" || fail "concrete HeadlessToolkit FontPeer overlay missing"
grep -q 'private synchronized ClasspathFontPeer rg35xxFontPeer' "$PEER" || fail "font peer cache synchronization missing"
grep -q 'RG35XX: unable to initialize OpenType font peer' "$OT" || fail "OpenTypeFontPeer is not fail-closed"
grep -q 'int required = offset + count;' "$ZONE" || fail "compound-glyph capacity correction missing"
[ -s "$FONT_STAGE" ] || fail "staged DejaVu runtime payload missing"

cat > "$MAKE_OVERLAY" <<'EOF'
# Generated by RGJ-RC1-011K/011O. Included from pinned src/libretro/Makefile.common.
include rg35xx/rc1_sources.mk
SOURCES_C += $(RG35XX_NATIVE_SRCS)
INCLUDES += $(RG35XX_NATIVE_CFLAGS)
# RG35XX Original/GarlicOS target uses pthread-backed worker/pipe ownership.
# Makefile already owns -lm through LIBM; add pthread to compile and link phases.
CFLAGS += -pthread
CXXFLAGS += -pthread
LDFLAGS += -pthread
EOF

# Integrate exactly once, after upstream declarations. Makefile includes Makefile.common
# before OBJECTS are calculated, so RG35XX source units become normal OBJECTS rather than
# a second build/link path.
printf '\n# RG35XX RC1 consolidated native source overlay\ninclude rg35xx/rc1_make_overlay.mk\n' >> "$MAKE_COMMON"
[ "$(grep -c '^include rg35xx/rc1_make_overlay\.mk$' "$MAKE_COMMON")" = 1 ] || fail "Make overlay include count is not exactly one"
grep -q '^INCLUDES += $(RG35XX_NATIVE_CFLAGS)$' "$MAKE_OVERLAY" || fail "native include flags are not wired to upstream INCLUDES"
grep -q '^LDFLAGS += -pthread$' "$MAKE_OVERLAY" || fail "pthread link requirement missing"

# 011N deployment manifest: build-time source and target runtime destination are distinct.
# Packaging/deployment must copy SOURCE to TARGET exactly; the Classpath fonts.properties
# points to TARGET and must never contain a disposable build-host path.
FONT_SHA=$(sha256sum "$FONT_STAGE" | awk '{print $1}')
cat > "$RG35XX_ASSEMBLY_ROOT/rg35xx_runtime_files.list" <<EOF
TYPE=font
SOURCE=$FONT_STAGE
TARGET=$RG35XX_FONT_RUNTIME_PATH
SHA256=$FONT_SHA
EOF
grep -Fq "TARGET=$RG35XX_FONT_RUNTIME_PATH" "$RG35XX_ASSEMBLY_ROOT/rg35xx_runtime_files.list" || fail "runtime deployment target missing"
if grep -Fq "$RG35XX_RUNTIME_ASSEMBLY_ROOT" "$RG35XX_RUNTIME_ASSEMBLY_ROOT/gnu/java/awt/font/fonts.properties"; then
  fail "fonts.properties leaked disposable assembly path"
fi

COUNT=$(find "$LIBRETRO_ROOT" -maxdepth 1 -name freej2me_libretro.c | wc -l | tr -d ' ')
[ "$COUNT" = 1 ] || fail "expected one freej2me_libretro.c, found $COUNT"
for f in media_cache media_event_queue audio_dispatch audio_pipe mixer midi_backend tsf_worker tsf_impl soundfont_source media_runtime; do
  [ -f "$LIBRETRO_ROOT/rg35xx/rg35xx_${f}.c" ] || fail "missing native unit rg35xx_${f}.c"
done

# Object-graph sanity: all ten project C units must be present in the source overlay once.
SRC_COUNT=$(grep -c '^  rg35xx/rg35xx_.*\.c' "$SOURCES_OVERLAY" | tr -d ' ')
[ "$SRC_COUNT" = 10 ] || fail "expected 10 RG35XX native source units, found $SRC_COUNT"

note "RUNTIME/FONT/NATIVE MAKE OVERLAY STRUCTURE PASS"
note "Pinned Makefile.common now includes the RG35XX overlay exactly once in the disposable source tree."
note "RG35XX native include flags use upstream INCLUDES; pthread is wired to compile and link phases."
note "Font runtime mapping is deployment-safe and compound-glyph Zone growth is guarded."
note "Deployment manifest: $RG35XX_ASSEMBLY_ROOT/rg35xx_runtime_files.list"
note "No BUILD-PASS: Classpath/JamVM compilation, Vietnamese/compound glyph smoke probes and ARMv5TE/uClibc compile/link remain required."
