import java.awt.image.BufferedImage;
import java.io.File;
import java.io.PrintWriter;
import javax.imageio.ImageIO;

public final class P2AExpectedGenerator {
    private static int hash1(int[] p) {
        int h=0x13579BDF;
        for (int i=0;i<p.length;i++) h=h*33+p[i];
        return h;
    }
    private static int hash2(int[] p) {
        int h=0x2468ACE0;
        for (int i=0;i<p.length;i++) h=h*65599+(p[i]^(p[i]>>>16));
        return h;
    }
    private static String hex(int v) {
        String s=Integer.toHexString(v);
        StringBuffer b=new StringBuffer(8);
        for(int i=s.length();i<8;i++) b.append('0');
        b.append(s); return b.toString();
    }
    private static String name(int i) {
        if(i<10) return "f00"+i+".png";
        if(i<100) return "f0"+i+".png";
        return "f"+i+".png";
    }
    public static void main(String[] a) throws Exception {
        File dir=new File(a[0]);
        PrintWriter out=new PrintWriter(a[1],"UTF-8");
        out.println("# PINNED_JDK8_IMAGEIO_EXPECTED");
        for(int i=0;i<150;i++) {
            String n=name(i);
            BufferedImage img=ImageIO.read(new File(dir,n));
            if(img==null) throw new RuntimeException("ImageIO null "+n);
            int w=img.getWidth(),h=img.getHeight();
            int[] p=img.getRGB(0,0,w,h,null,0,w);
            out.println(n+"\t"+w+"\t"+h+"\t"+hex(hash1(p))+"\t"+hex(hash2(p)));
        }
        out.close();
    }
}
