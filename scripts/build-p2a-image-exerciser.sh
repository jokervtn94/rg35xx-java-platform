# Generate the complete legal PNG matrix. Expected pixels are NOT generated by
# this Python code; pinned JDK8 ImageIO below is the canonical expected source.
python3 - "$RES/p2a" "$FIXTURE_MANIFEST" <<'PY'
import os, struct, sys, zlib
out, manifest = sys.argv[1:]
W, H = 9, 8
specs = [
    (0, [1,2,4,8,16]),
    (2, [8,16]),
    (3, [1,2,4,8]),
    (4, [8,16]),
    (6, [8,16]),
]
channels = {0:1, 2:3, 3:1, 4:2, 6:4}
passes = [(0,0,8,8),(4,0,8,8),(0,4,4,8),(2,0,4,4),(0,2,2,4),(1,0,2,2),(0,1,1,2)]

def chunk(t, data):
    tb=t.encode('ascii')
    return struct.pack('>I',len(data))+tb+data+struct.pack('>I',zlib.crc32(tb+data)&0xffffffff)

def maxv(depth): return (1<<depth)-1 if depth < 16 else 65535

def samples(ct, depth, x, y):
    m=maxv(depth)
    if ct == 0:
        return [((x*3 + y*5 + 1) * (m if m < 17 else 257) + x + y) % (m+1)]
    if ct == 2:
        return [
            (x*997 + y*313 + 0x1234) % (m+1),
            (x*557 + y*911 + 0x3456) % (m+1),
            (x*211 + y*733 + 0x5678) % (m+1),
        ]
    if ct == 3:
        return [(x + 3*y + (x*y)) % (m+1)]
    if ct == 4:
        return [
            (x*701 + y*383 + 0x1111) % (m+1),
            (x*193 + y*821 + 0x2222) % (m+1),
        ]
    return [
        (x*997 + y*313 + 0x1234) % (m+1),
        (x*557 + y*911 + 0x3456) % (m+1),
        (x*211 + y*733 + 0x5678) % (m+1),
        (x*389 + y*677 + 0x789a) % (m+1),
    ]

def pack_values(vals, depth):
    if depth == 8:
        return bytes(v & 0xff for v in vals)
    if depth == 16:
        b=bytearray()
        for v in vals: b.extend(((v>>8)&0xff, v&0xff))
        return bytes(b)
    b=bytearray((len(vals)*depth + 7)//8)
    bit=0
    mask=(1<<depth)-1
    for v in vals:
        byte=bit>>3
        shift=8-depth-(bit&7)
        b[byte] |= (v & mask) << shift
        bit += depth
    return bytes(b)

def paeth(a,b,c):
    p=a+b-c; pa=abs(p-a); pb=abs(p-b); pc=abs(p-c)
    if pa <= pb and pa <= pc: return a
    if pb <= pc: return b
    return c

def filter_row(raw, prev, ft, bpp):
    if ft == 0: return raw
    out=bytearray(len(raw))
    for i,v in enumerate(raw):
        left = raw[i-bpp] if i >= bpp else 0
        up = prev[i] if prev is not None else 0
        ul = prev[i-bpp] if prev is not None and i >= bpp else 0
        if ft == 1: pred=left
        elif ft == 2: pred=up
        elif ft == 3: pred=(left+up)//2
        elif ft == 4: pred=paeth(left,up,ul)
        else: raise ValueError(ft)
        out[i]=(v-pred)&0xff
    return bytes(out)

def row_bytes(ct, depth, coords):
    vals=[]
    for x,y in coords: vals.extend(samples(ct,depth,x,y))
    return pack_values(vals, depth)

def scan_data(ct, depth, interlace, ft):
    bpp=max(1,(channels[ct]*depth+7)//8)
    data=bytearray()
    if not interlace:
        prev=None
        for y in range(H):
            raw=row_bytes(ct,depth,[(x,y) for x in range(W)])
            data.append(ft); data.extend(filter_row(raw,prev,ft,bpp)); prev=raw
    else:
        for sx,sy,dx,dy in passes:
            xs=list(range(sx,W,dx)); ys=list(range(sy,H,dy))
            if not xs or not ys: continue
            prev=None
            for y in ys:
                raw=row_bytes(ct,depth,[(x,y) for x in xs])
                data.append(ft); data.extend(filter_row(raw,prev,ft,bpp)); prev=raw
    return bytes(data)

def palette(depth):
    n=1<<depth
    p=bytearray(); a=bytearray()
    for i in range(n):
        p.extend(((i*73+19)&255,(i*151+47)&255,(i*199+91)&255))
        a.append((i*41+17)&255)
    if n > 1: a[1]=0
    return bytes(p),bytes(a)

def trns(ct, depth):
    s=samples(ct,depth,0,0)
    if ct == 0: return struct.pack('>H',s[0])
    if ct == 2: return struct.pack('>HHH',s[0],s[1],s[2])
    return None

def make_png(ct,depth,interlace,ft):
    png=b'\x89PNG\r\n\x1a\n'
    png += chunk('IHDR',struct.pack('>IIBBBBB',W,H,depth,ct,0,0,interlace))
    if ct == 3:
        p,a=palette(depth); png += chunk('PLTE',p); png += chunk('tRNS',a)
    elif ct in (0,2):
        png += chunk('tRNS',trns(ct,depth))
    payload=zlib.compress(scan_data(ct,depth,interlace,ft),9)
    png += chunk('IDAT',payload)+chunk('IEND',b'')
    return png

rows=[]; idx=0
for ct,depths in specs:
    for depth in depths:
        for interlace in (0,1):
            for ft in range(5):
                name='f%03d.png'%idx
                data=make_png(ct,depth,interlace,ft)
                with open(os.path.join(out,name),'wb') as f: f.write(data)
                rows.append('%s\tCT%d\tBD%d\tI%d\tF%d\t%d\n'%(name,ct,depth,interlace,ft,len(data)))
                idx += 1
if idx != 150: raise SystemExit('fixture count %d'%idx)
with open(manifest,'w',encoding='ascii') as f:
    f.write('FILE\tCOLOR_TYPE\tBIT_DEPTH\tINTERLACE\tFILTER\tBYTES\n')
    f.writelines(rows)
print('P2A_EXERCISER_FIXTURE_GENERATION=PASS')
print('P2A_EXERCISER_FIXTURE_COUNT=%d'%idx)
PY

